# ID3v1.1 keeps provenance in the MP3 when it is saved outside MediSpace.
AI_AUDIO_TAG = pack(
    "3s30s30s30s4s28sBBB", b"TAG", b"AI-generated audio", b"ElevenLabs",
    b"MediSpace", b"", b"AI-generated by ElevenLabs", 0, 0, 255,
)


class ElevenLabsError(Exception):
    def __init__(self, code, http_status=None):
        self.code = code
        self.http_status = http_status
        super().__init__(code)


def elevenlabs_settings():
    lookup_key = os.getenv("ELEVENLABS_API_KEY", "").strip()
    voice = os.getenv("ELEVENLABS_VOICE_ID", "").strip()
    model_id = os.getenv("ELEVENLABS_MODEL_ID", "").strip() or "eleven_multilingual_v2"
    if lookup_key and re.fullmatch(r"[a-zA-Z0-9_-]{1,100}", voice):
        return lookup_key, voice, model_id
    return None


def synthesize_elevenlabs(message_text, settings):
    lookup_key, voice, model_id = settings
    if not re.fullmatch(r"[!-~]+", lookup_key):
        raise ElevenLabsError("ELEVENLABS_CLAVE")
    try:
        reply = httpx2.post(
            f"https://api.elevenlabs.io/v1/text-to-speech/{voice}",
            params={"output_format": "mp3_22050_32"},
            headers={"xi-api-key": lookup_key, "Accept": "audio/mpeg"},
            json={"text": message_text, "model_id": model_id},
            timeout=10,
        )
    except httpx2.RequestError:
        raise ElevenLabsError("ELEVENLABS_RED") from None
    if not reply.is_success:
        try:
            data = reply.json()
        except (ValueError, RecursionError):
            data = None
        if isinstance(data, dict):
            for detail_text in (data.get("detail"), data.get("error"), data):
                if not isinstance(detail_text, dict):
                    continue
                for field_name in ("code", "status"):
                    value = detail_text.get(field_name)
                    if isinstance(value, str) and value in PROVIDER_ERRORS:
                        raise ElevenLabsError(PROVIDER_ERRORS[value], reply.status_code)
        raise ElevenLabsError(HTTP_ERRORS.get(reply.status_code, "ELEVENLABS_SERVICIO"), reply.status_code)
    mime = reply.headers.get("Content-Type", "").split(";", 1)[0].strip().lower()
    if mime not in {"audio/mpeg", "audio/mp3"} or not reply.content:
        raise ElevenLabsError("ELEVENLABS_AUDIO", reply.status_code)
    audio = reply.content
    if audio[-128:-125] == b"TAG":
        audio = audio[:-128]
    return audio + AI_AUDIO_TAG
